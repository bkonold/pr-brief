#!/usr/bin/env python3
"""Write docs/prompt.md, the document that shows how the brief's content is produced, from the prompt sources.

usage: prompt_doc.py [--check]

The prompts are built by run.py's `build_prompts` with the `brief` variant from this folder, an invented pull request
and an invented repository context, so the document holds the real rules, the real answer shape and the real prompt
layout. `--check` writes nothing and exits 1 when docs/prompt.md differs from what this program would write.
"""
import argparse
import re
import sys
import tomllib
from pathlib import Path
from typing import Any

from run import build_prompts

ROOT: Path = Path(__file__).resolve().parent
DOC: Path = ROOT / "docs" / "prompt.md"
VARIANT: Path = ROOT / "variants" / "brief.toml"

PR: dict[str, Any] = {
    "title": "Add a nickname to the profile page",
    "body": "",
    "headRefName": "nickname",
    "commits": [
        {"messageHeadline": "Accept a nickname in the profile route"},
        {"messageHeadline": "Store the nickname with the profile"},
    ],
}

